// Writes worker/deals/sample-images.ts from the example pictures in
// worker/deals/samples/*.jpg (the examples the panel sends to a channel):
// the Worker keeps them in its own code, so they go as files, with no
// address to fetch. Run after changing a picture:
//   node scripts/deals-samples.mjs
import {readFileSync,writeFileSync} from "node:fs";
const names=["game-free","nuuvem","store","product"];
const dir=new URL("../worker/deals/samples/",import.meta.url);
const lines=names.map(n=>{
 const bytes=readFileSync(new URL(`${n}.jpg`,dir));
 if(bytes[0]!==0xff||bytes[1]!==0xd8||bytes.length>300_000)throw new Error(`${n}.jpg: a JPEG up to 300 KB`);
 return ` "${n}":"${bytes.toString("base64")}",`;
});
writeFileSync(new URL("../worker/deals/sample-images.ts",import.meta.url),`// Generated by scripts/deals-samples.mjs from worker/deals/samples/*.jpg.\n// The example posts' pictures (base64 JPEG).\nexport const sampleImages={\n${lines.join("\n")}\n} as const;\nexport type SampleImage=keyof typeof sampleImages;\n`);
console.log("sample-images.ts:",names.join(", "));
